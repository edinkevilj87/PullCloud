    /// <summary>Alphabetical list of places whose time zone exists on this PC.</summary>
    public static readonly List<WorldPlace> All = Raw
        .Where(r => Tz.TryGet(r.tz, out _))
        .Select(r => new WorldPlace(r.name, r.tz))
        .OrderBy(p => p.Name, StringComparer.OrdinalIgnoreCase)
        .ToList();

    /// <summary>Places that match a search text (city or country, accents and case ignored). Prefix matches first.</summary>
    public static List<WorldPlace> Filter(IEnumerable<WorldPlace> places, string text)
    {
        var q = Util.Norm(text ?? "").Trim();
        if (q == "") return places.ToList();
        return places
            .Select(p => (p, n: Util.Norm(p.Name)))
            .Where(x => x.n.Contains(q))
            .OrderBy(x => x.n.StartsWith(q) ? 0 : x.n.Contains(" " + q) ? 1 : 2)
            .ThenBy(x => x.p.Name, StringComparer.OrdinalIgnoreCase)
            .Select(x => x.p)
            .ToList();
    }
